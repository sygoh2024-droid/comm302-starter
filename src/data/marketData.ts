// Helper to generate realistic price curves
function generateTimeSeries(basePrice: number, pointsCount: number, volatility: number, trend: number): ChartPoint[] {
  const points: ChartPoint[] = [];
  let currentPrice = basePrice * (1 - trend * 0.03);
  const now = new Date(2024, 9, 28, 16, 0); // October 28, 2024

  for (let i = 0; i < pointsCount; i++) {
    const progress = i / (pointsCount - 1);
    // Smooth wander with occasional spikes
    const noise = (Math.sin(i * 0.4) * 0.5 + Math.cos(i * 0.2) * 0.5 + (Math.random() - 0.48)) * volatility * basePrice * 0.004;
    const trendEffect = progress * trend * basePrice * 0.02;
    currentPrice = Math.max(basePrice * 0.5, currentPrice + noise + (trendEffect / pointsCount));
    
    // Time label
    const pointDate = new Date(now.getTime() - (pointsCount - 1 - i) * (24 * 3600 * 1000 / (pointsCount / 5)));
    const timeStr = pointsCount <= 30 
      ? `${(9 + Math.floor(i * 0.25)).toString().padStart(2, '0')}:${((i * 15) % 60).toString().padStart(2, '0')}`
      : pointDate.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });

    const open = currentPrice - (Math.random() - 0.5) * volatility * basePrice * 0.002;
    const close = currentPrice;
    const high = Math.max(open, close) + Math.random() * volatility * basePrice * 0.003;
    const low = Math.min(open, close) - Math.random() * volatility * basePrice * 0.003;
    const volume = Math.floor(100000 + Math.random() * 800000);

    points.push({
      time: timeStr,
      price: Number(currentPrice.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  // Ensure last point hits target
  if (points.length > 0) {
    points[points.length - 1].price = basePrice;
    points[points.length - 1].close = basePrice;
  }
  return points;
}

function buildChartSet(basePrice: number, isBullish: boolean): Record<Timeframe, ChartPoint[]> {
  const trend = isBullish ? 1.4 : -0.8;
  return {
    '1D': generateTimeSeries(basePrice, 28, 1.2, trend * 0.6),
    '5D': generateTimeSeries(basePrice, 35, 1.8, trend * 0.9),
    '1M': generateTimeSeries(basePrice, 30, 2.2, trend * 1.5),
    '6M': generateTimeSeries(basePrice, 45, 2.8, trend * 2.2),
    'YTD': generateTimeSeries(basePrice, 50, 3.2, trend * 2.8),
    '1Y': generateTimeSeries(basePrice, 52, 3.5, trend * 3.4),
    'ALL': generateTimeSeries(basePrice, 60, 4.0, trend * 4.5),
  };
}

